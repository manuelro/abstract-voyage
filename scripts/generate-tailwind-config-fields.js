#!/usr/bin/env node
'use strict'

const fs = require('fs')
const path = require('path')
const resolveConfig = require('tailwindcss/resolveConfig')

const ROOT = path.resolve(__dirname, '..')
const OUTPUT_PATH = path.join(ROOT, 'components/Panel/config/tailwindUtilities.generated.ts')
const manifest = require('./tailwind-config-fields.manifest')
const tailwindConfig = resolveConfig(require(path.join(ROOT, 'tailwind.config.js')))

function cssLengthToPx(value) {
  if (Array.isArray(value)) return cssLengthToPx(value[0])
  if (typeof value !== 'string') return Number.POSITIVE_INFINITY
  const match = value.match(/^(-?\d*\.?\d+)(px|rem)$/)
  if (!match) return Number.POSITIVE_INFINITY
  return Number(match[1]) * (match[2] === 'rem' ? 16 : 1)
}

function orderedEntries(scale, sort) {
  const entries = Object.entries(scale)
  if (sort !== 'length') return entries
  return entries.sort(([leftKey, leftValue], [rightKey, rightValue]) => {
    const difference = cssLengthToPx(leftValue) - cssLengthToPx(rightValue)
    return difference || leftKey.localeCompare(rightKey, 'en', { numeric: true })
  })
}

function classNameFor(descriptor, token) {
  if (descriptor.formatter === 'tailwind-border-top-width') {
    return token === 'DEFAULT' ? 'border-t' : `border-t-${token}`
  }
  if (descriptor.formatter === 'tailwind-border-width') {
    return token === 'DEFAULT' ? 'border' : `border-${token}`
  }
  return `${descriptor.prefix}-${token}`
}

function labelFor(descriptor, scaleValue, className) {
  if (descriptor.labelFormatter === 'font-size') {
    return `${className} (${cssLengthToPx(scaleValue)}px)`
  }
  if (descriptor.labelFormatter === 'font-family') {
    return className.replace(/^(?:md:|lg:)?font-/, '').toUpperCase()
  }
  if (descriptor.labelFormatter === 'css-length') {
    return scaleValue === '0px' ? '0px (none)' : scaleValue
  }
  return className
}

function quote(value) {
  return JSON.stringify(value)
}

function generateSource() {
  const lines = [
    '/* AUTO-GENERATED by scripts/generate-tailwind-config-fields.js.',
    ' * Source: resolved tailwind.config.js + scripts/tailwind-config-fields.manifest.js.',
    ' * DO NOT EDIT BY HAND. Run `npm run generate:tailwind-fields` instead.',
    ' */',
    '',
    'export const TAILWIND_UTILITY_SETS = {',
  ]

  for (const [utilityName, descriptor] of Object.entries(manifest.utilities)) {
    const scale = tailwindConfig.theme[descriptor.scale]
    if (!scale || typeof scale !== 'object' || Array.isArray(scale)) {
      throw new Error(`Tailwind theme scale "${descriptor.scale}" for "${utilityName}" is not an object`)
    }

    const tokens = orderedEntries(scale, descriptor.sort)
      .filter(([token]) => !descriptor.tokens || descriptor.tokens.includes(token))
    if (descriptor.tokens?.some(token => !(token in scale))) {
      throw new Error(`Utility "${utilityName}" names a token missing from "${descriptor.scale}"`)
    }
    if (descriptor.control === 'enum' && tokens.length > 8) {
      throw new Error(`Utility "${utilityName}" has ${tokens.length} options and cannot use enum`)
    }

    lines.push(`  ${quote(utilityName)}: {`)
    for (const [breakpoint, variantPrefix] of Object.entries(manifest.breakpoints)) {
      lines.push(`    ${quote(breakpoint)}: {`)
      lines.push(`      control: ${quote(descriptor.control)},`)
      lines.push('      options: [')
      for (const [token, scaleValue] of tokens) {
        const value = `${variantPrefix}${classNameFor(descriptor, token)}`
        const label = labelFor(descriptor, scaleValue, value)
        lines.push(`        { label: ${quote(label)}, value: ${quote(value)}, cssValue: ${quote(scaleValue)} },`)
      }
      for (const semantic of descriptor.semanticOptions ?? []) {
        lines.push(`        { label: ${quote(semantic.label)}, value: ${quote(semantic.value)}, cssValue: ${quote(semantic.cssValue)} },`)
      }
      lines.push('      ],')
      lines.push('    },')
    }
    lines.push('  },')
  }

  lines.push(
    '} as const;',
    '',
    'export type TailwindUtilityName = keyof typeof TAILWIND_UTILITY_SETS;',
    'export type TailwindBreakpoint = keyof typeof TAILWIND_UTILITY_SETS[TailwindUtilityName];',
    'export type GeneratedTailwindTokenValue<',
    '  TUtility extends TailwindUtilityName,',
    "  TBreakpoint extends TailwindBreakpoint = 'base',",
    "> = typeof TAILWIND_UTILITY_SETS[TUtility][TBreakpoint]['options'][number]['value'];",
  )

  return `${lines.join('\n')}\n`
}

function main() {
  const source = generateSource()
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : ''
    if (current !== source) {
      console.error('Generated Tailwind config fields are stale. Run `npm run generate:tailwind-fields`.')
      process.exitCode = 1
    }
    return
  }

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true })
  fs.writeFileSync(OUTPUT_PATH, source)
  console.log(path.relative(ROOT, OUTPUT_PATH))
}

main()
